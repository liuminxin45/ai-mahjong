export function narrativeScene(n: DecisionNode, j: Pick<JourneyState, 'splitPair' | 'lost'>): NarrativeScene {
  const source = scenes[n.position - 1];
  if (!source) throw Error('这一页还没有写好。');
  const before = [...source.before], after = [...source.after];
  if (n.position === 11) before.unshift(j.splitPair ? '前面那对牌，被我拆开的地方，她在纸上画了两条短线。' : '前面那对牌还留着。她在旁边画了一个小小的圈。');
  if (n.position === 21) before.push(j.lost ? '刚才那一段失手，我没有往回翻。她给后面的题另画了记号。' : '刚才那一段得失还放在桌上。我把它拢好，照她留下的下一手重摆。');
  return { before, after, next: source.next };
}

export function narrativeResponse(n: DecisionNode, j: Pick<JourneyState, 'seed'>, tile: TileId): string[] {
  const lines: string[] = [`我把${tileName(tile)}推到桌上。`];
  if (n.position === 10) lines.push(tile === branchPair(n) ? '她看了一眼被分开的那对牌，拿笔在本子上划了两下。' : '她把还并在一起的那对牌轻轻往里推了推，没再拦着我的手。');
  if (n.position === 4) lines.push(n.question.context.hand.filter(t=>t===tile).length===2 ? '她伸手想把那张拦回来，手伸到一半，才想起已经说好让我打。' : '她把还并着的那对牌往里靠了靠，终于松开按着它们的手。');
  if (n.position === 3) lines.push('她又数了一遍桌上的四张七条，笔尖最后停在第四张旁边。');
  if (n.position === 6) lines.push(tile===n.question.certificate.fastest ? '她把“大的”两个字圈到一半，笔停住了。“那先试这条。”' : '她没再替我动牌，把两手撑在桌边，等着看剩下的路怎么走。');
  const result = outcome(n, j, tile);
  if (n.position >= 21) {
    if (result?.kind === 'you') lines.push('我把这手接着摆完。在这次重演里，是我这一席先和。');
    if (result?.kind === 'opponent') lines.push('我照谱上的记号继续往下摆。先和的是对面那一席。');
    if (result?.kind === 'draw') lines.push('把最后的余牌也摆完，这一局没有人和。');
    if (result?.kind === 'unfinished') lines.push('她只记到这里。我把这一段的牌收拢，留给下一页。');
    return lines;
  }
  if (result?.kind === 'you') lines.push('这一段里，轮到我把牌推倒。妹妹赶在舅舅开口前说：“我坐的这个位置，算我的。”');
  if (result?.kind === 'opponent') lines.push('舅舅把牌推倒，说了声“和了”。妹妹看了他一眼，又看了看我，伸手去够本子。');
  if (result?.kind === 'draw') lines.push('最后一张翻过来，谁也没有和。她先笑了：“那就谁也别说谁。”');
  if (result?.kind === 'unfinished') lines.push('纸上记下的这一小段，到这里就断了。后面还有另一手，她画了箭头。');
  return lines;
}

